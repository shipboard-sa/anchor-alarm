/**
 * Purpose: The anchor watch - C port of reference/anchorwatch/{geo,fit,watch}.py: ARM (rode pick), observe the
 *   swing, fit a circle (centre = anchor), LOCK and freeze it, ALARM when outside radius + tolerance for 20 s;
 *   CONSERVATIVE fallback floored at 2 x reach; coarse guard while ACQUIRING; DRAG? warning; GPS-stale warning.
 * Version: v2 (2026-10-02) - v2: aw_snapshot / aw_restore (power cut, 10-02)
 * Scope: PRODUCTION - anchor-box firmware, live on the box at the nav station since 2026-10-02 (installed by signed OTA).
 * Architecture: anchor-box firmware, pure C (math + string only, no ESP-IDF) so it is host-tested on the PC against
 *   scenarios generated by the Python reference (test_host/test_watch.c). Clock-free: the caller passes every
 *   timestamp (seconds). Fixed-size buffers inside aw_t (allocate it once, ~25 KB - PSRAM on the box). Feed at
 *   ~1 Hz (the reference's design rate). Context (water speed / wind) is not ported yet - messages only.
 * Invocation: imported by app_main.c / ui_watch.c and test_host/test_watch.c.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef enum { AW_OFF = 0, AW_ACQUIRING, AW_LOCKED, AW_CONSERVATIVE, AW_ALARM } aw_state_t;
typedef enum { AW_EV_STATE = 0, AW_EV_WARN, AW_EV_DRAG, AW_EV_INFO } aw_ev_kind_t;

typedef struct {
    double tolerance_m, debounce_s;
    double max_speed_mps, jump_margin_m;
    int reject_reset_count;
    double bin_s, fit_window_s;
    int min_fit_bins;
    double lock_min_s, min_arc_deg, max_rms_m, centre_stable_m, centre_stable_s, min_radius_m, max_radius_m,
        min_sagitta_ratio;
    double no_lock_after_s, stale_after_s;
    double bow_to_antenna_m;
    double trend_window_s;
    int trend_segments;
    double trend_min_slope_mps, trend_min_rise_m;
} aw_config_t;

void aw_default_config(aw_config_t *c);

typedef struct {
    double t;
    aw_ev_kind_t kind;
    aw_state_t state;      /* state after the event */
    char msg[192];
} aw_event_t;

#define AW_MAX_EVENTS 4

typedef struct { double t, x, y; } aw_bin_t;
typedef struct { double t, d; } aw_tpt_t;

#define AW_RAW_MAX   1200   /* ACQUIRING fixes: 900 s at 1 Hz + margin */
#define AW_BINS_MAX  128    /* fit window 900 s / 10 s bins = 90 */
#define AW_HIST_MAX  64     /* centre history ~ 200 s / 10 s */
#define AW_TREND_MAX 128    /* trend window 720 s / 10 s = 72 */

typedef struct {
    aw_config_t cfg;
    aw_state_t state;
    /* reset per arm */
    bool armed, have_frame, have_last, have_arm_point, have_fit, have_centre, stale, drag_suspected;
    double armed_at, lat0, lon0, kx;
    double last_t, last_x, last_y, last_lat, last_lon;
    int jump_streak, accepted;
    int rej_duplicate, rej_jump, rej_repeat, rej_filter_reset;
    double raw_x[AW_RAW_MAX], raw_y[AW_RAW_MAX];
    int n_raw;
    aw_bin_t bins[AW_BINS_MAX];
    int n_bins;
    bool bin_open;
    long bin_idx;
    double bin_st, bin_sx, bin_sy;
    int bin_n;
    double fit_cx, fit_cy, fit_r, fit_rms, fit_arc;
    int fit_n;
    aw_bin_t hist[AW_HIST_MAX];
    int n_hist;
    char no_lock_reason[160];
    double cx, cy, radius, alarm_radius;
    bool have_alarm_radius, locked, have_alarm_at;
    double locked_at, alarm_at;
    bool outside;
    double outside_since;
    bool have_distance;
    double distance;
    bool have_reach;
    double rode_ft, reach;
    double arm_x, arm_y;
    aw_tpt_t trend[AW_TREND_MAX];
    int n_trend;
    bool tbin_open;
    long tbin_idx;
    double tbin_st, tbin_sd;
    int tbin_n;
} aw_t;

void aw_init(aw_t *w, const aw_config_t *cfg);   /* cfg NULL = defaults */
int aw_arm(aw_t *w, double t, double rode_ft, aw_event_t *ev);       /* rode_ft <= 0 = none; returns #events */
int aw_disarm(aw_t *w, double t, aw_event_t *ev);
int aw_update(aw_t *w, double t, double lat, double lon, aw_event_t *ev);
int aw_tick(aw_t *w, double t, aw_event_t *ev);

/* power cut (10-02): the circle survives with NO age limit; dropped only by DISARM / a fresh ARM */
typedef struct {
    uint8_t version;          /* AW_SNAP_VERSION */
    uint8_t state;            /* aw_state_t: LOCKED / CONSERVATIVE / ALARM */
    uint8_t has_centre, locked;
    double lat, lon;          /* centre (or the arm point for a coarse-guard ALARM) */
    double radius, alarm_radius, rode_ft;
} aw_snapshot_t;
#define AW_SNAP_VERSION 1

bool aw_snapshot(const aw_t *w, aw_snapshot_t *s);             /* false while OFF / ACQUIRING */
int aw_restore(aw_t *w, double t, const aw_snapshot_t *s, aw_event_t *ev);

/* report */
const char *aw_state_name(aw_state_t s);
bool aw_centre_latlon(const aw_t *w, double *lat, double *lon, double *radius);  /* frozen, or provisional fit */
