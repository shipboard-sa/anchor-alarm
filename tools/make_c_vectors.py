"""
Purpose: Export boat-time test cases from the Python reference model into a C header for the host test of the
    C port (the rule: the C code must pass the same cases as reference/).
Version: v1 (2026-10-02)
Scope: STANDALONE UTILITY - anchor-box test tooling.
Architecture: reads reference/anchorwatch/boattime.py (already checked against IANA tz + astral by
    reference/tests/test_boattime.py); writes test_host/boattime_vectors.h, compiled into test_host/test_boattime.c.
Invocation: reference\\.venv\\Scripts\\python tools\\make_c_vectors.py   (run from code\\anchor-box; test_host\\run.bat
    does it for you)
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "reference"))
sys.path.insert(0, os.path.join(ROOT, "reference", "tests"))

from anchorwatch import boattime as bt          # noqa: E402
from test_boattime import HARBOURS, _instants    # noqa: E402


def main() -> None:
    lines = ["/* GENERATED by tools/make_c_vectors.py from reference/anchorwatch/boattime.py - do not edit. */",
             "#pragma once", "#include <stdint.h>", ""]

    rows = []
    for _place, lat, lon, _iana in HARBOURS:
        z = bt.zone_at(lat, lon)
        for t in _instants():
            rows.append(f'    {{ {lat!r}, {lon!r}, "{z.zid}", {t}LL, {bt.offset_min(z, t)} }},')
    for lat, lon in ((32.0, -65.0), (29.0, -100.0), (5.0, -30.0), (40.0, 179.0)):
        z = bt.zone_at(lat, lon)
        rows.append(f'    {{ {lat!r}, {lon!r}, "{z.zid}", 1790000000LL, {bt.offset_min(z, 1790000000)} }},')
    lines += ["typedef struct { double lat, lon; const char *zid; int64_t t; int off; } zone_case_t;",
              "static const zone_case_t ZONE_CASES[] = {", *rows, "};", ""]

    rows = []
    for lat, lon in ((29.95, -90.07), (25.05, -77.35), (12.15, -68.27), (18.47, -66.11), (-33.9, 151.2),
                     (60.0, 10.0)):
        for d in range(0, 366, 23):
            for h in range(0, 24, 3):
                t = (bt.days_from_civil(2026, 1, 1) + d) * 86400 + h * 3600 + 1234
                rows.append(f"    {{ {lat!r}, {lon!r}, {t}LL, {bt.sun_altitude_deg(t, lat, lon)!r} }},")
    lines += ["typedef struct { double lat, lon; int64_t t; double alt; } sun_case_t;",
              "static const sun_case_t SUN_CASES[] = {", *rows, "};", ""]

    out = os.path.join(ROOT, "test_host", "boattime_vectors.h")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
